import {existsSync} from 'node:fs';
import {spawn} from 'node:child_process';
import {resolve} from 'node:path';
if(existsSync('.env')) process.loadEnvFile('.env');
const command=process.argv[2];
if(!['dev','build','start','typegen'].includes(command)) throw new Error('Expected dev, build, start or typegen');
const args=[resolve('node_modules/next/dist/bin/next'),command,'apps/web',...(command==='build'?['--webpack']:command==='typegen'?[]:['--hostname','127.0.0.1','--port',process.env.WEB_PORT??'3000'])];
const child=spawn(process.execPath,args,{stdio:'inherit',windowsHide:true,env:process.env});
child.on('error',()=>{console.error('Could not start Next.js');process.exitCode=1;});
child.on('exit',code=>{process.exitCode=code??1;});
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,()=>child.kill(signal));
